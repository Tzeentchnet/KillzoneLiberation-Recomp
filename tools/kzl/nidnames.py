#!/usr/bin/env python3
"""Build research/nid_names.tsv (NID -> function name) from a PPSSPP checkout's HLE tables.

    nidnames.py <ppsspp>/Core/HLE [--out=research/nid_names.tsv]

PPSSPP lists every HLE function as {0xNID, &Wrap..., "name", ...} in Core/HLE/*.cpp. Only the
NID and the name are kept; the table is plain facts (numbers and names), no PPSSPP code.
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ENTRY = re.compile(r'\{\s*0[xX]([0-9A-Fa-f]{8})\s*,\s*[^,"]*,\s*"([A-Za-z_][A-Za-z0-9_]*)"')


def load(path=None):
    """Read the TSV back as {nid: name}."""
    path = path or os.path.join(ROOT, "research", "nid_names.tsv")
    names = {}
    if os.path.exists(path):
        with open(path, encoding="ascii") as f:
            for line in f:
                if line.startswith("#") or not line.strip():
                    continue
                nid, name = line.split("\t")[:2]
                names[int(nid, 16)] = name.strip()
    return names


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    opts = dict((o[2:].split("=", 1) + [""])[:2] for o in argv[1:] if o.startswith("--"))
    if len(args) != 1:
        sys.stderr.write(__doc__)
        return 2
    names = {}
    for p in sorted(glob.glob(os.path.join(args[0], "*.cpp"))):
        with open(p, encoding="utf-8", errors="replace") as f:
            for m in ENTRY.finditer(f.read()):
                names.setdefault(int(m.group(1), 16), m.group(2))
    out = opts.get("out") or os.path.join(ROOT, "research", "nid_names.tsv")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("# NID\tname  (generated by tools/kzl/nidnames.py from PPSSPP Core/HLE tables)\n")
        for nid in sorted(names):
            f.write(f"{nid:08x}\t{names[nid]}\n")
    print(f"wrote {out}: {len(names)} NIDs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
